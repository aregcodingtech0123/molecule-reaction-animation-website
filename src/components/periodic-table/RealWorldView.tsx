"use client";

import { AnimatePresence, motion } from "framer-motion";
import { Eye } from "lucide-react";
import { GasCloudVisualization } from "@/components/periodic-table/GasCloudVisualization";
import { SolidPlaceholderView } from "@/components/periodic-table/SolidPlaceholderView";
import { isGaseousAtSTP } from "@/lib/periodic-table/physical-state";
import type { ChemicalElement } from "@/lib/periodic-table/types";
import { cn } from "@/lib/utils";

interface RealWorldViewProps {
  element: ChemicalElement;
  className?: string;
}

/**
 * The element's phase as an illustration drawn by this site (SEO-19, Part 2). It used to show the lead image of the
 * element's Wikipedia article, fetched at runtime: every such image is a Wikimedia Commons file with its own licence
 * and author, which the page never credited. Owner rule: no image whose licence and attribution we cannot satisfy, so
 * the site's own generated visual is the only one, and no request leaves for Wikipedia.
 */
export function RealWorldView({ element, className }: RealWorldViewProps) {
  const isGas = isGaseousAtSTP(element.atomicNumber);

  return (
    <section className={cn("space-y-2", className)}>
      <div className="flex items-center gap-2">
        <Eye className="h-3.5 w-3.5 text-teal-600 dark:text-teal-400" />
        <h3 className="text-xs font-semibold uppercase tracking-[0.18em] text-teal-700 dark:text-teal-300/85">
          Phase illustration
        </h3>
      </div>

      <AnimatePresence mode="wait">
        <motion.div
          key={`${element.atomicNumber}-${isGas ? "gas" : "condensed"}`}
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          exit={{ opacity: 0, y: -8 }}
          transition={{ duration: 0.32 }}
          className="space-y-2"
        >
          {isGas ? <GasCloudVisualization element={element} /> : <SolidPlaceholderView element={element} />}
          <p className="text-[10px] text-neutral-600 dark:text-neutral-400">
            Illustration generated by this site, not a photograph.
          </p>
        </motion.div>
      </AnimatePresence>
    </section>
  );
}
