/** SEO-19 (Part 2): no third-party image whose licence we cannot credit — the panel draws its own illustration. */
import { screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { renderWithProviders } from "../../support/mocks";
import { RealWorldView } from "@/components/periodic-table/RealWorldView";
import { ELEMENTS } from "@/lib/periodic-table/elements";

describe("RealWorldView", () => {
  it("for all 118 elements: no request at all, no <img>, the site's own illustration with a caption saying so", async () => {
    const fetchSpy = vi.fn(() => Promise.reject(new Error("no network expected")));
    vi.stubGlobal("fetch", fetchSpy);
    for (const el of ELEMENTS) {
      const { container, unmount } = renderWithProviders(<RealWorldView element={el} />);
      expect(container.querySelector("img"), el.symbol).toBeNull();
      expect(container.querySelector('a[href*="wikipedia"]'), el.symbol).toBeNull();
      expect(screen.getByText("Illustration generated by this site, not a photograph."), el.symbol).toBeTruthy();
      expect(container.textContent, el.symbol).not.toMatch(/Wikipedia/i);
      unmount();
    }
    await new Promise((r) => setTimeout(r, 20));
    expect(fetchSpy).not.toHaveBeenCalled();
  });
});
